static int ensure_dir(const char *path)
{
  struct stat st;
  if (stat(path, &st) == 0) {
    if (S_ISDIR(st.st_mode)) {
      return 0;
    }
    fprintf(stderr, "error: not a directory: %s\n", path);
    return -1;
  }
  if (mkdir(path, 0755) != 0 && errno != EEXIST) {
    fprintf(stderr, "error: mkdir %s: %s\n", path, strerror(errno));
    return -1;
  }
  return 0;
}

static int ensure_emit_dir(const char *root)
{
  char p[4096];
  if ((size_t)snprintf(p, sizeof p, "%s/src", root) >= sizeof p) {
    fprintf(stderr, "error: path too long (src)\n");
    return -1;
  }
  if (ensure_dir(p) != 0) return -1;
  if ((size_t)snprintf(p, sizeof p, "%s/src/systems", root) >= sizeof p) {
    fprintf(stderr, "error: path too long (systems)\n");
    return -1;
  }
  if (ensure_dir(p) != 0) return -1;
  if ((size_t)snprintf(p, sizeof p, "%s/src/systems/emit", root) >= sizeof p) {
    fprintf(stderr, "error: path too long (emit)\n");
    return -1;
  }
  return ensure_dir(p);
}

static int write_bytes(const char *path, const unsigned char *data, size_t n)
{
  FILE *f = fopen(path, "wb");
  size_t w;
  if (!f) {
    fprintf(stderr, "error: open %s: %s\n", path, strerror(errno));
    return -1;
  }
  w = fwrite(data, 1, n, f);
  if (w != n) {
    fprintf(stderr, "error: short write %s (%zu of %zu)\n", path, w, n);
    fclose(f);
    return -1;
  }
  if (fclose(f) != 0) {
    fprintf(stderr, "error: close %s: %s\n", path, strerror(errno));
    return -1;
  }
  return 0;
}

